#!/usr/bin/env node
/**
 * Generates migrations/0006_block_prohibited_content.sql from src/prohibited.js.
 *
 * The triggers make D1 itself refuse listings that match the prohibited-content
 * blocklist, whichever code path writes them (Worker, pipelines, manual SQL).
 * RAISE(IGNORE) silently skips the offending row, so one bad row can't fail a
 * whole batch import — every pipeline also filters before writing.
 *
 * Usage: node scripts/ops/build-prohibited-triggers.js   (re-run after editing the list)
 * Apply: the "apply-sql" task in ops/tasks.json, or `wrangler d1 execute hv-directory --remote --file=...`
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { PROHIBITED_TERMS } = require('../../src/prohibited.js');

for (const t of PROHIBITED_TERMS) {
  if (!/^[\p{Ll}\p{Lo}\p{N} -]+$/u.test(t)) throw new Error(`Unsafe term for SQL inlining: ${t}`);
}

const matches = (expr) => PROHIBITED_TERMS.map(t => `instr(${expr}, '${t}') > 0`).join('\n    OR ');

const sitesText = `lower(NEW.url || ' ' || COALESCE(json_extract(NEW.data_json, '$.name'), '') || ' ' || COALESCE(json_extract(NEW.data_json, '$.description'), ''))`;
const queueText = `lower(NEW.url || ' ' || COALESCE(NEW.name, ''))`;

const trigger = (name, when, table, text) => `DROP TRIGGER IF EXISTS ${name};
-- statement-break
CREATE TRIGGER ${name} BEFORE ${when} ON ${table}
  WHEN ${matches(text)}
BEGIN
  SELECT RAISE(IGNORE);
END;
-- statement-break`;

const sql = `-- Generated by scripts/ops/build-prohibited-triggers.js from src/prohibited.js — do not edit by hand.
-- Blocks listings matching the prohibited-content blocklist at the database level.
${trigger('block_prohibited_sites_insert', 'INSERT', 'sites', sitesText)}
${trigger('block_prohibited_sites_update', 'UPDATE OF url, data_json', 'sites', sitesText)}
${trigger('block_prohibited_queue_insert', 'INSERT', 'queue', queueText)}
${trigger('block_prohibited_queue_update', 'UPDATE OF url, name', 'queue', queueText)}
`;

const out = path.join(__dirname, '..', '..', 'migrations', '0006_block_prohibited_content.sql');
fs.writeFileSync(out, sql);
console.log(`wrote ${path.relative(process.cwd(), out)} (${PROHIBITED_TERMS.length} terms, 4 triggers)`);
